import { createHash } from "node:crypto";

/**
 * The content of one warmup send — deliberately the smallest possible
 * model (Stage 9 spec section 6/13): no attachments, no arbitrary headers,
 * no template/campaign system. Never persisted — generated fresh from
 * `generateWarmupMessage` immediately before a send and held only in
 * memory for the duration of that one attempt (Stage 9 spec section 6:
 * "Do NOT store message bodies in audit logs... prefer generated/stable
 * metadata rather than persisting unnecessary sensitive content").
 *
 * `to` defaults to the sending mailbox's own address (self-send). Stage 20
 * may pass `toAddress` when warmup-network routing is enabled; omitting it
 * preserves the Stage 9 default so existing tests and `WARMUP_NETWORK_ROUTING_MODE=off`
 * stay self-send.
 */
export interface WarmupMessage {
  readonly to: string;
  readonly subject: string;
  readonly body: string;
}

export interface GenerateWarmupMessageInput {
  readonly fromAddress: string;
  /** Optional recipient. Defaults to `fromAddress` (self-send). */
  readonly toAddress?: string;
  /** The execution intent's own idempotency key — used only to seed deterministic, stable content, never persisted itself as part of the message. */
  readonly idempotencyKey: string;
}

/**
 * Pure and deterministic — the same `idempotencyKey` always produces the
 * same message content, so a retried attempt for the same execution slot
 * never sends a different email than the one before it. Content is
 * intentionally short, generic, and non-promotional (Stage 9 spec section
 * 13: "low-risk... non-promotional... clearly owned by the warmup
 * engine") — it exists only to exercise a mailbox's real send/receive
 * path, never to communicate anything to a human recipient.
 */
export function generateWarmupMessage(input: GenerateWarmupMessageInput): WarmupMessage {
  const digest = createHash("sha256").update(input.idempotencyKey).digest("hex").slice(0, 8);
  return {
    to: input.toAddress ?? input.fromAddress,
    subject: `Warmup check-in ${digest}`,
    body: `This is an automated deliverability check-in generated by Skout's email warmup service. No action is needed. Reference: ${digest}.`,
  };
}
